#!/usr/bin/env bash
# One-click replacement-NMF sweep: one linear layer per job, trained on PDB.
#
# Each job exact-matches a single 2D Linear and replaces only that layer
# (nmf.match_mode=exact, nmf.max_replacements=1). Parent modules such as
# Transition are never replaced as a group.
#
# LAYER_SET:
#   encoder  input-shaping linears (default)
#   proj     token/atom projection linears
#   head     output-head linears
#   all      union of the three families
#   one      a single LAYER=module.path job
#
# Optional:
#   INCLUDE_BASELINE=1  also run a no-NMF PDB baseline
#   PRESET=a6000        GPU-appropriate training sizes (see "GPU sizing" below)
#
# Wall-clock: the sweep is a plain sequential loop of jobs on ONE GPU. With
# spare cards, split the families and share a single sweep directory so every
# result still lands in one report:
#   D=/backup01/zzj/logs/train_nmf_zkp_pdb/sweep_shared
#   GPU=2 SWEEP_DIR=$D INCLUDE_BASELINE=1 LAYER_SET=proj    bash .../run_nmf_zkp_pdb_sweep.sh &
#   GPU=4 SWEEP_DIR=$D INCLUDE_BASELINE=0 LAYER_SET=encoder bash .../run_nmf_zkp_pdb_sweep.sh &
#   GPU=5 SWEEP_DIR=$D INCLUDE_BASELINE=0 LAYER_SET=head    bash .../run_nmf_zkp_pdb_sweep.sh &
#   wait
#   python models/rfd3/scripts/summarize_nmf_zkp_pdb_sweep.py $D --seed 42
#   python models/rfd3/scripts/plot_nmf_zkp_pdb_metrics.py $D --ckpt <ckpt>
# Run the baseline in exactly ONE invocation. Each invocation rewrites
# comparison_table.md from the exit codes present at that moment, so once all
# jobs finish treat paper_summary.* / paper_metrics.* (regenerated by the two
# commands above) as the authoritative report. Keep the total number of
# dataloader workers across the concurrent jobs <= available CPU cores.
#
# Ran out of time before the loop finished? Everything below (comparison_table,
# paper_summary, figures, paper_training_cost) is written ONLY after the last
# job returns, so a killed run leaves none of them. Per-job artefacts are still
# on disk, so build the report from those instead:
#   python models/rfd3/scripts/report_partial_sweep.py --out <OUT_DIR> \
#     [--discover <LOG_ROOT>] [--drop-incomplete] <sweep dir ...>
# It labels every setting complete / training-only and refuses to invent a
# holdout number for a job that was stopped before its validation pass.
#
# Usage:
#   bash models/rfd3/scripts/run_nmf_zkp_pdb_sweep.sh
#   LAYER_SET=one LAYER=token_initializer.process_pll bash models/rfd3/scripts/run_nmf_zkp_pdb_sweep.sh
#   DATA=... PARQUET=... PDB_MIRROR=... PROJECT_ROOT=/backup01/zzj/protein/foundry LOG_ROOT=... CKPT=... PYTHON=python SEED=42 MAX_EPOCHS=5
#   GPU=2  (default: use idle RTX A6000 GPU 2; set GPU=4 if needed)

