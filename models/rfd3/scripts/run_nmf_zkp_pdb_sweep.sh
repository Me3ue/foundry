# ---------------------------------------------------------------------------
# GPU sizing. The plain defaults (D=4 diffusion samples, 1920-atom crop, 2
# dataloader workers) were sized for a ~12 GiB card. Pick a preset for the
# card actually in use; explicit env vars always win over the preset:
#   PRESET=a6000    48 GiB A6000, safe first step   (D=16, 1920 atoms, 8 workers)
#   PRESET=a6000xl  48 GiB, larger crop -- PROBE the peak memory before a sweep
#   PRESET=small    ~12 GiB; same as the plain defaults, spelled out
#
# Why these numbers: the dominant activation is the atom-pair tensor, so peak
# VRAM ~ D * L^2 with L = min(crop_size * ~14, max_atoms_in_crop). Relative to
# the old default (D=4, L=1920 -> 14.7M units):
#   D=16, L=1920 -> 59M   (~4x, the a6000 preset)
#   D=16, L=2560 -> 105M  (~7x, the a6000xl preset -- do not start here blind)
# NOTE max_atoms_in_crop is the binding limit: CROP_SIZE=256 needs ~3584 atoms,
# so at MAX_ATOMS=1920 the effective crop is only ~137 residues.
# Validation always uses diffusion_batch_size=1, so a large D can never OOM the
# holdout pass. After a run, read the true peak from
# <sweep_dir>/<tag>.run_summary.json -> cost.gpu_peak_allocated_bytes
# (or watch: nvidia-smi --query-gpu=memory.used --format=csv -l 5).
#
# Wall-clock levers, in order of effect:
#   1. several GPUs at once (see the header recipe), 
#   2. NUM_WORKERS/PREFETCH (atomworks featurisation is CPU heavy; 32 cores),
#   3. DIFFUSION_BS: each loaded structure then yields D noise samples, so the
#      per-structure host cost is amortised. Those samples are correlated, so
#      lowering MAX_EPOCHS by ~2x (not by D) keeps the gradient quality.
# ---------------------------------------------------------------------------
case "${PRESET:-}" in
  ""|default) ;;
  small)
    : "${DIFFUSION_BS:=4}"; : "${CROP_SIZE:=256}"; : "${MAX_ATOMS:=1920}"
    : "${NUM_WORKERS:=2}"; : "${PREFETCH:=2}"
    ;;
  a6000)
    : "${DIFFUSION_BS:=16}"; : "${CROP_SIZE:=256}"; : "${MAX_ATOMS:=1920}"
    : "${NUM_WORKERS:=8}"; : "${PREFETCH:=4}"
    ;;
  a6000xl)
    : "${DIFFUSION_BS:=16}"; : "${CROP_SIZE:=256}"; : "${MAX_ATOMS:=2560}"
    : "${NUM_WORKERS:=8}"; : "${PREFETCH:=4}"
    ;;
  *)
    echo "Unknown PRESET=${PRESET}. Use small, a6000, a6000xl, or leave it unset." >&2
    exit 1
    ;;
esac
echo "PRESET=${PRESET:-default}  DIFFUSION_BS=${DIFFUSION_BS:-4}  CROP_SIZE=${CROP_SIZE:-256}  MAX_ATOMS=${MAX_ATOMS:-1920}  WORKERS=${NUM_WORKERS:-2}"

